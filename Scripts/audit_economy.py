#!/usr/bin/env python3
"""Inventory monetary definitions, mutations, and presentations without changing them."""
from pathlib import Path
import re

root = Path(__file__).resolve().parents[1]
pattern = re.compile(r'\b(?:cash|cashDelta|minimumCash|studentDebt|consumerDebt|medicalDebt|retirementBalance|retirementContributionPercent|mortgageBalance|mortgageMonthlyPayment|annualIncome|annualCost|purchasePrice|price|installationPrice|annualUpkeep|unemploymentSupport|requestedDebtCharge|restrictedDeposit|saleProceeds|rentalIncome|expectedMarketRent|livingCost|incomeMultiplier|housingCostMultiplier|livingCostMultiplier)\b|\$[0-9]')
entries = []
for path in sorted((root / 'OneLife').glob('*')):
    if path.suffix not in {'.swift', '.json'}:
        continue
    for line_number, line in enumerate(path.read_text().splitlines(), 1):
        if pattern.search(line):
            entries.append((str(path.relative_to(root)), line_number, line.strip()))
out = root / 'Documentation/Working/ECONOMY_MONEY_INVENTORY.md'
lines = ['# Economy monetary inventory', '',
         'Generated by `python3 Scripts/audit_economy.py`. This includes authored content, requirements, rates, accounting, compatibility fields, and displayed dollar amounts. The economy specification defines the active rules; legacy compatibility fields are retained for save decoding.', '',
         '| Source | Occurrences |', '| --- | ---: |']
for path in sorted({entry[0] for entry in entries}):
    lines.append(f'| `{path}` | {sum(entry[0] == path for entry in entries)} |')
lines += ['', f'Total: {len(entries)} monetary references.', '', '## References', '']
for path in sorted({entry[0] for entry in entries}):
    lines += [f'### {path}', '', '```text']
    lines += [f'{number}: {line}' for source, number, line in entries if source == path]
    lines += ['```', '']
out.write_text('\n'.join(lines))
print(f'{len(entries)} monetary references written to {out.relative_to(root)}')
